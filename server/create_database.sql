-- https://stackoverflow.com/questions/3327312/how-can-i-drop-all-the-tables-in-a-postgresql-database
DROP SCHEMA PUBLIC CASCADE;

CREATE SCHEMA PUBLIC;

GRANT ALL ON SCHEMA PUBLIC TO POSTGRES;

GRANT ALL ON SCHEMA PUBLIC TO PUBLIC;

-- https://docs.postgrest.org/en/v12/tutorials/tut0.html#step-4-run-postgrest
DROP ROLE WEB_ANON;

DROP ROLE AUTHENTICATOR;

CREATE ROLE WEB_ANON NOLOGIN;

CREATE ROLE AUTHENTICATOR NOINHERIT LOGIN PASSWORD 'mysecretpassword';

GRANT WEB_ANON TO AUTHENTICATOR;

-- создание базы данных
CREATE TYPE CHAT_TYPE_ENUM AS ENUM('Private', 'Group', 'Channel');

CREATE TYPE ROLE_TYPE_ENUM AS ENUM('Owner', 'Administrator', 'Participant');

-- таблица пользователей
CREATE TABLE USERS (
	USER_ID SERIAL PRIMARY KEY,
	USERNAME TEXT NOT NULL UNIQUE CHECK (USERNAME <> ''),
	PASSWORD VARCHAR(32) NOT NULL
);

-- таблица контактов, то как пользователи называют друг друга, либо кто с кем знаком.
CREATE TABLE CONTACTS (
	USER_1 SERIAL NOT NULL REFERENCES USERS (USER_ID) CHECK (USER_1 <> USER_2),
	USER_2 SERIAL NOT NULL REFERENCES USERS (USER_ID) CHECK (USER_2 <> USER_1),
	NICKNAME VARCHAR(255) NOT NULL CHECK (NICKNAME <> ''),
	PRIMARY KEY (USER_1, USER_2)
);

-- таблица чатов и их типы
CREATE TABLE CHATS (
	CHAT_ID SERIAL PRIMARY KEY,
	TITLE VARCHAR(255) NOT NULL CHECK (TITLE <> ''),
	CHAT_TYPE CHAT_TYPE_ENUM NOT NULL
);

CREATE TABLE PARTICIPANTS (
	CHAT_ID SERIAL NOT NULL REFERENCES CHATS (CHAT_ID),
	USER_ID SERIAL NOT NULL REFERENCES USERS (USER_ID),
	PRIMARY KEY (CHAT_ID, USER_ID)
);

CREATE TABLE ROLES (
	CHAT_ID SERIAL NOT NULL REFERENCES CHATS (CHAT_ID),
	USER_ID SERIAL NOT NULL REFERENCES USERS (USER_ID),
	ROLE_TYPE ROLE_TYPE_ENUM NOT NULL,
	PRIMARY KEY (CHAT_ID, USER_ID)
);

CREATE TABLE MESSAGES (
	MESSAGE_ID SERIAL PRIMARY KEY,
	CHAT_ID SERIAL NOT NULL REFERENCES CHATS (CHAT_ID),
	MESSAGE_TEXT TEXT NOT NULL CHECK (MESSAGE_TEXT <> '')
);

-- waveform 255/4=63 csv значения. Считается автоматически, создать вью?
CREATE TABLE VOICES (
	VOICE_ID SERIAL PRIMARY KEY,
	MESSAGE_ID SERIAL NOT NULL REFERENCES MESSAGES (MESSAGE_ID),
	MEDIA_URL TEXT NOT NULL CHECK (STARTS_WITH(MEDIA_URL, 'file://')),
	WAVEFORM VARCHAR(255)
);

-- base64 картинка для предпросмотра, создать вью?
CREATE TABLE IMAGES (
	IMAGE_ID SERIAL PRIMARY KEY,
	MESSAGE_ID SERIAL NOT NULL REFERENCES MESSAGES (MESSAGE_ID),
	MEDIA_URL TEXT NOT NULL CHECK (STARTS_WITH(MEDIA_URL, 'file://')),
	PREVIEW TEXT
);

CREATE TABLE FILES (
	FILE_ID SERIAL PRIMARY KEY,
	MESSAGE_ID SERIAL NOT NULL REFERENCES MESSAGES (MESSAGE_ID),
	MEDIA_URL TEXT NOT NULL CHECK (STARTS_WITH(MEDIA_URL, 'file://'))
);

